"""Generate the SeekThenHide mystic items with Blender (bpy).

    python build_mystic_items.py                      # all items, final quality
    python build_mystic_items.py --items RuneStone    # just one
    python build_mystic_items.py --res 512 --preview 600 --samples 48   # quick look

Needs Blender 4.2+ as a Python module (`pip install bpy`) or run through
`blender -b --python build_mystic_items.py -- <args>`.
"""
import argparse
import math
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import bpy  # noqa: E402

import mi_core as C  # noqa: E402
import mi_items  # noqa: E402


def parse():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else sys.argv[1:]
    ap = argparse.ArgumentParser()
    ap.add_argument('--items', default='')
    ap.add_argument('--out', default=os.path.normpath(os.path.join(HERE, '..')))
    ap.add_argument('--res', type=int, default=0, help='override texture resolution')
    ap.add_argument('--preview', type=int, default=1400)
    ap.add_argument('--samples', type=int, default=192)
    ap.add_argument('--no-preview', action='store_true')
    ap.add_argument('--hp-preview', action='store_true', help='also render the hp source mesh')
    ap.add_argument('--look', action='store_true', help='only build + render the hp mesh (fast look-dev)')
    return ap.parse_args(argv)


def build(item, args):
    t0 = time.time()
    key = item.key
    print(f"== {key}", flush=True)
    C.reset_scene()
    col_hp = C.collection('HP')
    col_lp = C.collection(key)
    item.setup()

    hp_parts = item.build('hp')
    hp = C.join(hp_parts['body'], f"{key}_HP", col_hp)
    if args.look:
        hglass = C.join(hp_parts['glass'], 'glass', col_hp) if hp_parts['glass'] else None
        if hglass:
            C.set_material(hglass, item.glass_material())
            hglass.hide_render = True
        C.bake_vertex_ao(hp, item.ao_distance)
        if hglass:
            hglass.hide_render = False
        C.studio(C.collection('Studio'), *item_frame(hp))
        C.render_preview(os.path.join(args.out, 'Previews', f"{key}_look.png"), *item_frame(hp),
                         res=args.preview, samples=args.samples, **item.view)
        return dict(key=key, title=item.title, tris=C.tri_count(hp), res=0, secs=round(time.time() - t0))
    for g in hp_parts['glass']:
        bpy.data.objects.remove(g)
    lp_parts = item.build('lp')
    island_angle = item.island_angle or item.sharp
    body = [C.unwrap_part(p, island_angle) for p in lp_parts['body']]
    lp = C.join(body, f"SM_{key}", col_lp)
    glass = None
    if lp_parts['glass']:
        glass = C.join([C.unwrap_part(p, island_angle) for p in lp_parts['glass']], f"SM_{key}_Glass", col_lp)
    print(f"   hp {C.tri_count(hp):,} tris, lp {C.tri_count(lp):,} tris", flush=True)

    C.bake_vertex_ao(hp, item.ao_distance)
    t1 = time.time()
    C.prepare_lowpoly(lp, sharp_angle=item.sharp)
    print(f"   lp triangulated {C.tri_count(lp):,} tris", flush=True)
    res = args.res or item.res
    tex_dir = os.path.join(args.out, 'Textures', key)
    images = C.bake_down(hp, lp, res, item.extrusion, item.max_ray, tex_dir, key)
    tex, paths = C.finish_textures(images, tex_dir, key)
    print(f"   unwrap + bake {time.time() - t1:.0f}s", flush=True)
    C.set_material(lp, C.game_material(key, tex, item.emit_strength))
    objs = [lp]
    if glass is not None:
        glass.data.shade_smooth()
        glass.data.set_sharp_from_angle(angle=math.radians(70))
        C.set_material(glass, item.glass_material())
        glass.parent = lp
        objs.append(glass)

    if args.hp_preview:
        C.studio(C.collection('Studio'), *item_frame(lp))
        lp.hide_render = True
        if glass:
            glass.hide_render = True
        C.render_preview(os.path.join(args.out, 'Previews', f"{key}_hp.png"), *item_frame(hp),
                         res=args.preview, samples=args.samples, **item.view)

    # the hp source is regenerated by this script, so keep it out of the shipped .blend
    hp_mesh = hp.data
    bpy.data.objects.remove(hp)
    bpy.data.meshes.remove(hp_mesh)
    lp.hide_render = False
    if glass:
        glass.hide_render = False

    C.export_item(objs, os.path.join(args.out, 'Export', 'FBX', f"SM_{key}.fbx"),
                  os.path.join(args.out, 'Export', 'GLB', f"SM_{key}.glb"))

    if not args.no_preview:
        if 'Studio' not in bpy.data.collections:
            C.studio(C.collection('Studio'), *item_frame(lp))
        C.render_preview(os.path.join(args.out, 'Previews', f"{key}.png"), *item_frame(lp),
                         res=args.preview, samples=args.samples, **item.view)

    for ob in list(bpy.data.objects):
        if ob.name.startswith('PRJ_'):
            bpy.data.objects.remove(ob)
    os.makedirs(os.path.join(args.out, 'Blend'), exist_ok=True)
    bpy.ops.wm.save_as_mainfile(filepath=os.path.join(args.out, 'Blend', f"{key}.blend"),
                                compress=True, relative_remap=True)
    info = dict(key=key, title=item.title, tris=C.tri_count(lp) + (C.tri_count(glass) if glass else 0),
                res=res, secs=round(time.time() - t0))
    print(f"   done {info}", flush=True)
    return info


def item_frame(ob):
    from mathutils import Vector
    pts = [ob.matrix_world @ Vector(c) for c in ob.bound_box]
    lo = Vector((min(p.x for p in pts), min(p.y for p in pts), min(p.z for p in pts)))
    hi = Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))
    center = (lo + hi) / 2
    radius = (hi - lo).length / 2
    return tuple(center), radius


def main():
    args = parse()
    wanted = [s for s in args.items.split(',') if s]
    infos = []
    for cls in mi_items.ITEMS:
        if wanted and cls.key not in wanted:
            continue
        infos.append(build(cls(), args))
    for i in infos:
        print(f"{i['key']:<14} {i['tris']:>7,} tris  {i['res']}px  {i['secs']}s")


if __name__ == '__main__':
    main()
